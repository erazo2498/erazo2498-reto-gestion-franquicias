package com.pragma.franquicias.r2dbc.branch;

import com.pragma.franquicias.model.branch.Branch;
import com.pragma.franquicias.model.branch.exceptions.DuplicateBranchNameException;
import com.pragma.franquicias.model.branch.gateways.SaveBranchGateway;
import com.pragma.franquicias.model.franchise.exceptions.FranchiseNotFoundException;
import io.r2dbc.spi.R2dbcException;
import lombok.RequiredArgsConstructor;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.data.r2dbc.core.R2dbcEntityTemplate;
import org.springframework.stereotype.Repository;
import reactor.core.publisher.Mono;

@Repository
@RequiredArgsConstructor
public class BranchAdapter implements SaveBranchGateway {

    private static final String FOREIGN_KEY_VIOLATION = "23503";

    private final R2dbcEntityTemplate template;

    // An explicit insert: the id is generated by the application, so Spring Data's save() would try an UPDATE.
    @Override
    public Mono<Branch> save(Branch branch) {
        return template.insert(toData(branch))
                .map(this::toEntity)
                .onErrorMap(
                        DuplicateKeyException.class,
                        error -> new DuplicateBranchNameException(branch.getName()))
                .onErrorMap(
                        this::isForeignKeyViolation,
                        error -> new FranchiseNotFoundException(branch.getFranchiseId()));
    }

    // Spring reports every integrity violation with the same class; the SQLSTATE tells a missing franchise apart.
    private boolean isForeignKeyViolation(Throwable error) {
        return error instanceof DataIntegrityViolationException
                && error.getCause() instanceof R2dbcException cause
                && FOREIGN_KEY_VIOLATION.equals(cause.getSqlState());
    }

    private BranchData toData(Branch branch) {
        return new BranchData(branch.getId(), branch.getFranchiseId(), branch.getName());
    }

    private Branch toEntity(BranchData data) {
        return Branch.builder().id(data.id()).franchiseId(data.franchiseId()).name(data.name()).build();
    }
}
