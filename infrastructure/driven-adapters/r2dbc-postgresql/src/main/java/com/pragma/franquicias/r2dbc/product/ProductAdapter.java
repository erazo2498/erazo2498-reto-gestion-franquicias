package com.pragma.franquicias.r2dbc.product;

import static org.springframework.data.relational.core.query.Criteria.where;

import com.pragma.franquicias.model.branch.BranchTopProduct;
import com.pragma.franquicias.model.branch.exceptions.BranchNotFoundException;
import com.pragma.franquicias.model.product.Product;
import com.pragma.franquicias.model.product.exceptions.DuplicateProductNameException;
import com.pragma.franquicias.model.product.gateways.DeleteProductGateway;
import com.pragma.franquicias.model.product.gateways.FindTopStockProductsGateway;
import com.pragma.franquicias.model.product.gateways.RenameProductGateway;
import com.pragma.franquicias.model.product.gateways.SaveProductGateway;
import com.pragma.franquicias.model.product.gateways.UpdateProductStockGateway;
import io.r2dbc.spi.R2dbcException;
import io.r2dbc.spi.Readable;
import java.util.Optional;
import java.util.UUID;
import lombok.RequiredArgsConstructor;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.data.r2dbc.core.R2dbcEntityTemplate;
import org.springframework.data.relational.core.query.Query;
import org.springframework.data.relational.core.query.Update;
import org.springframework.stereotype.Repository;
import reactor.core.publisher.Flux;
import reactor.core.publisher.Mono;

@Repository
@RequiredArgsConstructor
public class ProductAdapter
        implements SaveProductGateway,
                DeleteProductGateway,
                UpdateProductStockGateway,
                FindTopStockProductsGateway,
                RenameProductGateway {

    // One statement for the whole franchise: for each branch, the LATERAL subquery picks its product of highest stock.
    // Ties are broken by the name (ignoring case) and then by the id, so the answer is always the same. A branch
    // without products still produces a row, with null product columns (LEFT JOIN).
    private static final String TOP_STOCK_PRODUCTS = """
            SELECT b.id AS branch_id, b.name AS branch_name,
                   p.id AS product_id, p.name AS product_name, p.stock AS product_stock
            FROM branch b
            LEFT JOIN LATERAL (
                SELECT id, name, stock FROM product
                WHERE branch_id = b.id
                ORDER BY stock DESC, lower(name), id
                LIMIT 1
            ) p ON true
            WHERE b.franchise_id = :franchiseId
            ORDER BY lower(b.name), b.id
            """;


    private static final String FOREIGN_KEY_VIOLATION = "23503";

    private final R2dbcEntityTemplate template;

    // An explicit insert: the id is generated by the application, so Spring Data's save() would try an UPDATE.
    @Override
    public Mono<Product> save(Product product) {
        return template.insert(toData(product))
                .map(this::toEntity)
                .onErrorMap(
                        DuplicateKeyException.class,
                        error -> new DuplicateProductNameException(product.getName()))
                .onErrorMap(
                        this::isForeignKeyViolation,
                        error -> new BranchNotFoundException(product.getBranchId()));
    }

    // A single statement scoped to the branch: a product of another branch is never touched, and deleting a product
    // that is already gone is not an error, so the number of deleted rows is ignored.
    @Override
    public Mono<Void> delete(UUID branchId, UUID productId) {
        return template.delete(
                        Query.query(where("id").is(productId).and(where("branchId").is(branchId))), ProductData.class)
                .then();
    }

    // The update is scoped to the branch, like the delete. It completes empty when no row matched, so the use case
    // can tell the client the product was not found; otherwise the updated product is read back.
    @Override
    public Mono<Product> updateStock(UUID branchId, UUID productId, int stock) {
        Query scope = Query.query(where("id").is(productId).and(where("branchId").is(branchId)));
        return template.update(scope, Update.update("stock", stock), ProductData.class)
                .filter(updatedRows -> updatedRows > 0)
                .flatMap(updatedRows -> template.selectOne(scope, ProductData.class))
                .map(this::toEntity);
    }

    // Renames the product scoped to its branch. Completes empty when no row matched.
    @Override
    public Mono<Product> rename(UUID branchId, UUID productId, String name) {
        Query scope = Query.query(where("id").is(productId).and(where("branchId").is(branchId)));
        return template.update(scope, Update.update("name", name), ProductData.class)
                .filter(updatedRows -> updatedRows > 0)
                .flatMap(updatedRows -> template.selectOne(scope, ProductData.class))
                .map(this::toEntity)
                .onErrorMap(DuplicateKeyException.class, error -> new DuplicateProductNameException(name));
    }

    @Override
    public Flux<BranchTopProduct> findByFranchise(UUID franchiseId) {
        return template.getDatabaseClient()
                .sql(TOP_STOCK_PRODUCTS)
                .bind("franchiseId", franchiseId)
                .map((row, metadata) -> toBranchTopProduct(row))
                .all();
    }

    private BranchTopProduct toBranchTopProduct(Readable row) {
        UUID branchId = row.get("branch_id", UUID.class);
        Optional<Product> topProduct = Optional.ofNullable(row.get("product_id", UUID.class))
                .map(productId -> Product.builder()
                        .id(productId)
                        .branchId(branchId)
                        .name(row.get("product_name", String.class))
                        .stock(row.get("product_stock", Integer.class))
                        .build());
        return BranchTopProduct.builder()
                .branchId(branchId)
                .branchName(row.get("branch_name", String.class))
                .product(topProduct)
                .build();
    }

    // Spring reports every integrity violation with the same class; the SQLSTATE tells a missing branch apart.
    private boolean isForeignKeyViolation(Throwable error) {
        return error instanceof DataIntegrityViolationException
                && error.getCause() instanceof R2dbcException cause
                && FOREIGN_KEY_VIOLATION.equals(cause.getSqlState());
    }

    private ProductData toData(Product product) {
        return new ProductData(product.getId(), product.getBranchId(), product.getName(), product.getStock());
    }

    private Product toEntity(ProductData data) {
        return Product.builder()
                .id(data.id())
                .branchId(data.branchId())
                .name(data.name())
                .stock(data.stock())
                .build();
    }
}
