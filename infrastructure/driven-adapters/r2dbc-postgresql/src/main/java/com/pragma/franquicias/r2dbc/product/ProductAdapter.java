package com.pragma.franquicias.r2dbc.product;

import com.pragma.franquicias.model.branch.exceptions.BranchNotFoundException;
import com.pragma.franquicias.model.product.Product;
import com.pragma.franquicias.model.product.exceptions.DuplicateProductNameException;
import com.pragma.franquicias.model.product.gateways.SaveProductGateway;
import io.r2dbc.spi.R2dbcException;
import lombok.RequiredArgsConstructor;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.data.r2dbc.core.R2dbcEntityTemplate;
import org.springframework.stereotype.Repository;
import reactor.core.publisher.Mono;

@Repository
@RequiredArgsConstructor
public class ProductAdapter implements SaveProductGateway {

    private static final String FOREIGN_KEY_VIOLATION = "23503";

    private final R2dbcEntityTemplate template;

    // An explicit insert: the id is generated by the application, so Spring Data's save() would try an UPDATE.
    @Override
    public Mono<Product> save(Product product) {
        return template.insert(toData(product))
                .map(this::toEntity)
                .onErrorMap(
                        DuplicateKeyException.class,
                        error -> new DuplicateProductNameException(product.getName()))
                .onErrorMap(
                        this::isForeignKeyViolation,
                        error -> new BranchNotFoundException(product.getBranchId()));
    }

    // Spring reports every integrity violation with the same class; the SQLSTATE tells a missing branch apart.
    private boolean isForeignKeyViolation(Throwable error) {
        return error instanceof DataIntegrityViolationException
                && error.getCause() instanceof R2dbcException cause
                && FOREIGN_KEY_VIOLATION.equals(cause.getSqlState());
    }

    private ProductData toData(Product product) {
        return new ProductData(product.getId(), product.getBranchId(), product.getName(), product.getStock());
    }

    private Product toEntity(ProductData data) {
        return Product.builder()
                .id(data.id())
                .branchId(data.branchId())
                .name(data.name())
                .stock(data.stock())
                .build();
    }
}
