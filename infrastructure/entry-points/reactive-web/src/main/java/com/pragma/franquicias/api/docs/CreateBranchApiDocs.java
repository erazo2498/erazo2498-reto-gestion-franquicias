package com.pragma.franquicias.api.docs;

import static com.pragma.franquicias.api.docs.OpenApiSupport.componentsWithErrorSchema;
import static com.pragma.franquicias.api.docs.OpenApiSupport.error;
import static com.pragma.franquicias.api.docs.OpenApiSupport.jsonContent;
import static com.pragma.franquicias.api.docs.OpenApiSupport.response;

import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.Operation;
import io.swagger.v3.oas.models.PathItem;
import io.swagger.v3.oas.models.media.ObjectSchema;
import io.swagger.v3.oas.models.media.Schema;
import io.swagger.v3.oas.models.media.StringSchema;
import io.swagger.v3.oas.models.media.UUIDSchema;
import io.swagger.v3.oas.models.parameters.PathParameter;
import io.swagger.v3.oas.models.parameters.RequestBody;
import io.swagger.v3.oas.models.responses.ApiResponses;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.springdoc.core.customizers.OpenApiCustomizer;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

// The router stays free of documentation annotations: the OpenAPI description of the endpoint lives here.
@Configuration
public class CreateBranchApiDocs {

    private static final String PATH = "/api/v1/franchises/{franchiseId}/branches";
    private static final String SAMPLE_FRANCHISE_ID = "3f2b8c1e-7a4d-4e59-9c0a-1d6e5b8f2a47";

    @Bean
    public OpenApiCustomizer createBranchDocs() {
        return openApi -> {
            registerSchemas(openApi);
            openApi.path(PATH, new PathItem().post(createBranchOperation()));
        };
    }

    private void registerSchemas(OpenAPI openApi) {
        Components components = componentsWithErrorSchema(openApi);
        components.addSchemas("CreateBranchRequest", createBranchRequestSchema());
        components.addSchemas("BranchResponse", branchResponseSchema());
    }

    private Schema<?> createBranchRequestSchema() {
        return new ObjectSchema()
                .description("Data needed to create a branch.")
                .addProperty(
                        "name",
                        new StringSchema()
                                .minLength(1)
                                .maxLength(120)
                                .description("Branch name. Surrounding spaces are removed; it must be unique inside "
                                        + "its franchise, ignoring upper and lower case.")
                                .example("Centro"))
                .required(List.of("name"));
    }

    private Schema<?> branchResponseSchema() {
        return new ObjectSchema()
                .description("A branch of a franchise.")
                .addProperty("id", new UUIDSchema().description("Identifier generated by the API."))
                .addProperty("franchiseId", new UUIDSchema().description("Franchise the branch belongs to."))
                .addProperty("name", new StringSchema().description("Branch name, trimmed."))
                .required(List.of("id", "franchiseId", "name"));
    }

    private Operation createBranchOperation() {
        return new Operation()
                .operationId("createBranch")
                .summary("Add a branch to a franchise")
                .description("Creates a branch inside an existing franchise and returns it with its generated id. "
                        + "The name must be unique inside that franchise; other franchises may reuse it.")
                .addTagsItem("Branches")
                .addParametersItem(new PathParameter()
                        .name("franchiseId")
                        .description("Identifier of the franchise that will own the branch.")
                        .required(true)
                        .schema(new UUIDSchema())
                        .example(SAMPLE_FRANCHISE_ID))
                .requestBody(new RequestBody()
                        .required(true)
                        .content(jsonContent("CreateBranchRequest", "validName", "A valid name", request())))
                .responses(new ApiResponses()
                        .addApiResponse("201", response(
                                "Branch created", "BranchResponse", "created", "The new branch", created()))
                        .addApiResponse("400", response(
                                "Invalid data: missing, blank or too long name, malformed body, a name that is not "
                                        + "text, or a franchise id that is not a UUID",
                                "ErrorResponse",
                                "invalidName",
                                "Blank name",
                                error("INVALID_DATA", "Branch name must be between 1 and 120 characters")))
                        .addApiResponse("404", response(
                                "The franchise does not exist",
                                "ErrorResponse",
                                "franchiseNotFound",
                                "Unknown franchise",
                                error("FRANCHISE_NOT_FOUND", "Franchise '" + SAMPLE_FRANCHISE_ID + "' does not exist")))
                        .addApiResponse("409", response(
                                "The franchise already has a branch with that name (ignoring case)",
                                "ErrorResponse",
                                "duplicateName",
                                "Name already used in the franchise",
                                error("DUPLICATE_NAME", "A branch named 'Centro' already exists in this franchise")))
                        .addApiResponse("415", response(
                                "The request is not application/json",
                                "ErrorResponse",
                                "unsupportedMediaType",
                                "Wrong content type",
                                error("UNSUPPORTED_MEDIA_TYPE", "Content type must be application/json")))
                        .addApiResponse("500", response(
                                "Unexpected error; the details are only written to the server log",
                                "ErrorResponse",
                                "unexpectedError",
                                "Unexpected failure",
                                error("INTERNAL_ERROR", "Unexpected error"))));
    }

    private Map<String, Object> request() {
        Map<String, Object> value = new LinkedHashMap<>();
        value.put("name", "Centro");
        return value;
    }

    private Map<String, Object> created() {
        Map<String, Object> value = new LinkedHashMap<>();
        value.put("id", "9a1c4e72-5b3d-4f08-8e61-2c7d0a9b3f15");
        value.put("franchiseId", SAMPLE_FRANCHISE_ID);
        value.put("name", "Centro");
        return value;
    }
}
