package com.pragma.franquicias.api.docs;

import static com.pragma.franquicias.api.docs.OpenApiSupport.componentsWithErrorSchema;
import static com.pragma.franquicias.api.docs.OpenApiSupport.error;
import static com.pragma.franquicias.api.docs.OpenApiSupport.jsonContent;
import static com.pragma.franquicias.api.docs.OpenApiSupport.response;

import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.Operation;
import io.swagger.v3.oas.models.PathItem;
import io.swagger.v3.oas.models.media.IntegerSchema;
import io.swagger.v3.oas.models.media.ObjectSchema;
import io.swagger.v3.oas.models.media.Schema;
import io.swagger.v3.oas.models.media.StringSchema;
import io.swagger.v3.oas.models.media.UUIDSchema;
import io.swagger.v3.oas.models.parameters.PathParameter;
import io.swagger.v3.oas.models.parameters.RequestBody;
import io.swagger.v3.oas.models.responses.ApiResponses;
import java.math.BigDecimal;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.springdoc.core.customizers.OpenApiCustomizer;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

// The router stays free of documentation annotations: the OpenAPI description of the endpoint lives here.
@Configuration
public class CreateProductApiDocs {

    private static final String PATH = "/api/v1/branches/{branchId}/products";
    private static final String SAMPLE_BRANCH_ID = "9a1c4e72-5b3d-4f08-8e61-2c7d0a9b3f15";

    @Bean
    public OpenApiCustomizer createProductDocs() {
        return openApi -> {
            registerSchemas(openApi);
            openApi.path(PATH, new PathItem().post(createProductOperation()));
        };
    }

    private void registerSchemas(OpenAPI openApi) {
        Components components = componentsWithErrorSchema(openApi);
        components.addSchemas("CreateProductRequest", createProductRequestSchema());
        components.addSchemas("ProductResponse", productResponseSchema());
    }

    private Schema<?> createProductRequestSchema() {
        return new ObjectSchema()
                .description("Data needed to create a product.")
                .addProperty(
                        "name",
                        new StringSchema()
                                .minLength(1)
                                .maxLength(120)
                                .description("Product name. Surrounding spaces are removed; it must be unique inside "
                                        + "its branch, ignoring upper and lower case.")
                                .example("Hamburguesa"))
                .addProperty(
                        "stock",
                        new IntegerSchema()
                                .minimum(BigDecimal.ZERO)
                                .description("Initial stock: a whole number greater than or equal to 0. Decimals "
                                        + "and text are rejected, not converted.")
                                .example(10))
                .required(List.of("name", "stock"));
    }

    private Schema<?> productResponseSchema() {
        return new ObjectSchema()
                .description("A product of a branch.")
                .addProperty("id", new UUIDSchema().description("Identifier generated by the API."))
                .addProperty("branchId", new UUIDSchema().description("Branch the product belongs to."))
                .addProperty("name", new StringSchema().description("Product name, trimmed."))
                .addProperty("stock", new IntegerSchema().description("Current stock."))
                .required(List.of("id", "branchId", "name", "stock"));
    }

    private Operation createProductOperation() {
        return new Operation()
                .operationId("createProduct")
                .summary("Add a product to a branch")
                .description("Creates a product with its initial stock inside an existing branch and returns it with "
                        + "its generated id. The name must be unique inside that branch; other branches may reuse it.")
                .addTagsItem("Products")
                .addParametersItem(new PathParameter()
                        .name("branchId")
                        .description("Identifier of the branch that will own the product.")
                        .required(true)
                        .schema(new UUIDSchema())
                        .example(SAMPLE_BRANCH_ID))
                .requestBody(new RequestBody()
                        .required(true)
                        .content(jsonContent("CreateProductRequest", "validProduct", "A valid product", request())))
                .responses(new ApiResponses()
                        .addApiResponse("201", response(
                                "Product created", "ProductResponse", "created", "The new product", created()))
                        .addApiResponse("400", response(
                                "Invalid data: missing, blank or too long name; missing, negative, decimal or text "
                                        + "stock; malformed body; or a branch id that is not a UUID",
                                "ErrorResponse",
                                "invalidStock",
                                "Negative stock",
                                error(
                                        "INVALID_DATA",
                                        "Product stock is required and must be a whole number greater than or equal "
                                                + "to 0")))
                        .addApiResponse("404", response(
                                "The branch does not exist",
                                "ErrorResponse",
                                "branchNotFound",
                                "Unknown branch",
                                error("BRANCH_NOT_FOUND", "Branch '" + SAMPLE_BRANCH_ID + "' does not exist")))
                        .addApiResponse("409", response(
                                "The branch already has a product with that name (ignoring case)",
                                "ErrorResponse",
                                "duplicateName",
                                "Name already used in the branch",
                                error("DUPLICATE_NAME", "A product named 'Hamburguesa' already exists in this branch")))
                        .addApiResponse("415", response(
                                "The request is not application/json",
                                "ErrorResponse",
                                "unsupportedMediaType",
                                "Wrong content type",
                                error("UNSUPPORTED_MEDIA_TYPE", "Content type must be application/json")))
                        .addApiResponse("500", response(
                                "Unexpected error; the details are only written to the server log",
                                "ErrorResponse",
                                "unexpectedError",
                                "Unexpected failure",
                                error("INTERNAL_ERROR", "Unexpected error"))));
    }

    private Map<String, Object> request() {
        Map<String, Object> value = new LinkedHashMap<>();
        value.put("name", "Hamburguesa");
        value.put("stock", 10);
        return value;
    }

    private Map<String, Object> created() {
        Map<String, Object> value = new LinkedHashMap<>();
        value.put("id", "5d7e2a91-3c4b-4a6f-9b18-0e2f7c6d4a53");
        value.put("branchId", SAMPLE_BRANCH_ID);
        value.put("name", "Hamburguesa");
        value.put("stock", 10);
        return value;
    }
}
